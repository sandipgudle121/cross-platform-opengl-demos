    for (int i = 0; i < 764; i++)
    {
        model_textures[i] = sphereTexCoords[i];
    }
    
    for (int i = 0; i < 2280; i++)
    {
        model_elements[i] = sphereElements[i];
    }

    // process sphere's data using sphere header file
